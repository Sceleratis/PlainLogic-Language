"""The gold conversion pairs must satisfy the documents' own cases.

Python pairs run against tests generated by tools/case_to_tests.py;
TypeScript pairs run under Node's type stripping with assertions mirroring
the same cases; C# pairs compile and run under the .NET SDK when one is
available (skipped otherwise).
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import types
import unittest


sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]


def load(path: Path, name: str) -> types.ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


generator = load(ROOT / "tools" / "case_to_tests.py", "case_to_tests_for_gold")
case_tests = load(ROOT / "test" / "case_to_tests_test.py", "case_to_tests_test_for_gold")


PAIRS = [
    ("quote-total", "quote-total.plog", "quote_total", "quote_impl_gold",
     ["test_case_empty", "test_case_below_threshold", "test_case_threshold_and_rounding"]),
    ("mixed-total", "mixed-total.plog", "mixed_total", "mixed_impl_gold",
     ["test_case_empty", "test_case_mixed"]),
]

TS_DRIVER = """
import assert from "node:assert/strict";
import { quote } from "../quote-total/quoteTotal.ts";
import { totalPositive } from "../mixed-total/mixedTotal.ts";

assert.deepEqual(quote([]), { subtotalCents: 0, discountCents: 0, totalCents: 0 });
assert.deepEqual(quote([{ priceCents: 9999, quantity: 1 }]),
                 { subtotalCents: 9999, discountCents: 0, totalCents: 9999 });
assert.deepEqual(quote([{ priceCents: 10009, quantity: 1 }]),
                 { subtotalCents: 10009, discountCents: 1000, totalCents: 9009 });
assert.equal(totalPositive([]), 0);
assert.equal(totalPositive([-4, 0, 3, 5]), 8);
console.log("ts gold pairs OK");
"""


CS_PROGRAM = """
using System;
using System.Collections.Generic;

var failures = 0;
void Check(bool ok, string name)
{
    Console.WriteLine($"{(ok ? "PASS" : "FAIL")} {name}");
    if (!ok) failures++;
}

Check(QuoteTotal.Quote(new List<Line>()) == new Quote(0, 0, 0), "quote empty");
Check(QuoteTotal.Quote(new List<Line> { new(9999, 1) }) == new Quote(9999, 0, 9999), "quote below_threshold");
Check(QuoteTotal.Quote(new List<Line> { new(10009, 1) }) == new Quote(10009, 1000, 9009), "quote threshold_and_rounding");
Check(MixedTotal.TotalPositive(new List<int>()) == 0, "mixed empty");
Check(MixedTotal.TotalPositive(new List<int> { -4, 0, 3, 5 }) == 8, "mixed mixed");

Console.WriteLine(failures == 0 ? "CS GOLD PAIRS OK" : $"{failures} FAILURES");
return failures;
"""


def find_dotnet() -> str | None:
    found = shutil.which("dotnet")
    if found:
        return found
    local = Path.home() / ".dotnet" / "dotnet"
    return str(local) if local.exists() else None


class GoldConversionsTests(unittest.TestCase):
    def test_python_pairs_pass_the_generated_case_tests(self):
        case_tests.install_pytest_shim()
        for slug, document, module_file, module_name, test_names in PAIRS:
            with self.subTest(pair=slug):
                source = (ROOT / "examples" / document).read_text(encoding="utf-8")
                generated = generator.generate(source, "python", module_name, document)
                load(ROOT / "examples" / "conversions" / slug / f"{module_file}.py", module_name)
                with tempfile.TemporaryDirectory() as directory:
                    tests = case_tests.load_module(f"gold_tests_{slug.replace('-', '_')}", generated, directory)
                    for name in test_names:
                        getattr(tests, name)()

    def test_csharp_pairs_pass_the_case_assertions(self):
        dotnet = find_dotnet()
        if dotnet is None:
            self.skipTest("no .NET SDK available")
        conversions = ROOT / "examples" / "conversions"
        with tempfile.TemporaryDirectory(dir=conversions) as directory:
            work = Path(directory)
            env = dict(__import__("os").environ, DOTNET_CLI_TELEMETRY_OPTOUT="1", DOTNET_NOLOGO="1")
            created = subprocess.run([dotnet, "new", "console", "-o", str(work), "--force"],
                                     text=True, capture_output=True, env=env, check=False)
            self.assertEqual(created.returncode, 0, created.stdout + created.stderr)
            for source in ("quote-total/QuoteTotal.cs", "mixed-total/MixedTotal.cs"):
                (work / Path(source).name).write_text((conversions / source).read_text(encoding="utf-8"),
                                                       encoding="utf-8")
            (work / "Program.cs").write_text(CS_PROGRAM, encoding="utf-8")
            result = subprocess.run([dotnet, "run", "--project", str(work)],
                                    text=True, capture_output=True, env=env, check=False)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("CS GOLD PAIRS OK", result.stdout)

    def test_typescript_pairs_pass_the_case_assertions(self):
        with tempfile.TemporaryDirectory(dir=ROOT / "examples" / "conversions") as directory:
            driver = Path(directory) / "driver.ts"
            driver.write_text(TS_DRIVER, encoding="utf-8")
            result = subprocess.run(["node", str(driver)], text=True, capture_output=True, check=False)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
            self.assertIn("ts gold pairs OK", result.stdout)


if __name__ == "__main__":
    unittest.main()
